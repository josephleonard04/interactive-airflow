function allrun(c: AirflowCase): string {
  const snappy = c.obstacles.length > 0 ? 'runApplication snappyHexMesh -overwrite\n' : ''
  return `#!/bin/sh
cd "\${0%/*}" || exit 1
. "\${WM_PROJECT_DIR:?}/bin/tools/RunFunctions"

runApplication blockMesh
${snappy}runApplication topoSet
runApplication createPatch -overwrite
runApplication buoyantSimpleFoam

# The backend samples the final time directly; this is a convenience hook.
echo "Done. Latest time:" && foamListTimes -latestTime
`
}

function allclean(): string {
  return `#!/bin/sh
cd "\${0%/*}" || exit 1
. "\${WM_PROJECT_DIR:?}/bin/tools/CleanFunctions"
cleanCase
rm -rf constant/polyMesh/sets
`
}

function caseReadme(c: AirflowCase, inlets: string[], outlets: string[]): string {
  return `# OpenFOAM case: ${c.name}

Generated by the interactive_airflow accurate engine (buoyantSimpleFoam, laminar).

- Room: ${c.room.width} x ${c.room.depth} x ${c.room.height} m (W x D x H)
- Inlets: ${inlets.join(', ') || 'none'}
- Outlets: ${outlets.join(', ') || 'none'}
- Fans (fvOptions momentum): ${c.fans.length}
- Heat sources (fvOptions energy): ${c.heat.length}
- Obstacles (snappyHexMesh STL): ${c.obstacles.length}

## Run

\`\`\`sh
./Allrun        # blockMesh -> snappyHexMesh -> topoSet -> createPatch -> buoyantSimpleFoam
\`\`\`

Requires a sourced OpenFOAM environment (\`WM_PROJECT_DIR\` set). On Windows use
WSL or the OpenFOAM.com Docker image. See docs/openfoam-engine.md.

The local backend runs these steps for you and streams the solver log + the
sampled velocity/temperature field back to the web viewer.
`
}
