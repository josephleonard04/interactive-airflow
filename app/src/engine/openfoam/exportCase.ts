function blockMeshDict(c: AirflowCase): string {
  const { width: W, height: H, depth: D } = c.room
  const x0 = -W / 2
  const x1 = W / 2
  const z0 = -D / 2
  const z1 = D / 2
  // ~0.15 m cells -> a reasonable, fast indoor mesh before snappy refinement.
  const nx = Math.max(20, Math.round(W / 0.15))
  const ny = Math.max(12, Math.round(H / 0.15))
  const nz = Math.max(16, Math.round(D / 0.15))
  return (
    FOAM_HEADER('dictionary', 'blockMeshDict', 'system') +
    `
scale   1;

vertices
(
    (${x0} 0 ${z0})
    (${x1} 0 ${z0})
    (${x1} ${H} ${z0})
    (${x0} ${H} ${z0})
    (${x0} 0 ${z1})
    (${x1} 0 ${z1})
    (${x1} ${H} ${z1})
    (${x0} ${H} ${z1})
);

blocks
(
    hex (0 1 5 4 3 2 6 7) (${nx} ${nz} ${ny}) simpleGrading (1 1 1)
);

edges ();

boundary
(
    floor      { type wall; faces ( (0 1 5 4) ); }
    ceiling    { type wall; faces ( (3 7 6 2) ); }
    backWall   { type wall; faces ( (0 3 2 1) ); }
    frontWall  { type wall; faces ( (4 5 6 7) ); }
    leftWall   { type wall; faces ( (0 4 7 3) ); }
    rightWall  { type wall; faces ( (1 2 6 5) ); }
);

mergePatchPairs ();
`
  )
}

// Carve inlet/outlet face sets out of the rear (back) wall using axis-aligned
// boxes around each device, then createPatch promotes them to real patches.
function topoSetDict(c: AirflowCase): string {
  const actions: string[] = []
  const faceBox = (id: string, center: [number, number, number], size: [number, number]) => {
    const [cx, cy, cz] = center
    const [sw, sh] = size
    const min = vec([cx - sw / 2 - 0.05, cy - sh / 2 - 0.05, cz - 0.2])
    const max = vec([cx + sw / 2 + 0.05, cy + sh / 2 + 0.05, cz + 0.2])
    return `    {
        name    ${id}FaceSet;
        type    faceSet;
        action  new;
        source  boxToFace;
        sourceInfo { box ${min} ${max}; }
    }
    {
        name    ${id}FaceSet;
        type    faceSet;
        action  subset;
        source  patchToFace;
        sourceInfo { patch backWall; }
    }`
  }
  for (const i of c.inlets) actions.push(faceBox(`${i.id}Inlet`, i.center, i.size))
  for (const o of c.outlets) actions.push(faceBox(`${o.id}Outlet`, o.center, o.size))

  // Fan jet as a sphere cellZone for fvOptions.
  for (const f of c.fans) {
    actions.push(`    {
        name    ${f.id}Zone;
        type    cellZoneSet;
        action  new;
        source  sphereToCell;
        sourceInfo { centre ${vec(f.center)}; radius ${f.radius}; }
    }`)
  }
  // Heat sources as sphere cellZones for fvOptions.
  for (const h of c.heat) {
    actions.push(`    {
        name    ${h.id}Zone;
        type    cellZoneSet;
        action  new;
        source  sphereToCell;
        sourceInfo { centre ${vec(h.center)}; radius ${h.radius}; }
    }`)
  }

  return (
    FOAM_HEADER('dictionary', 'topoSetDict', 'system') +
    `
actions
(
${actions.join('\n')}
);
`
  )
}

function createPatchDict(c: AirflowCase): string {
  const patch = (name: string, set: string, type: string) => `    {
        name ${name};
        patchInfo { type ${type}; }
        constructFrom set;
        set ${set};
    }`
  const patches: string[] = []
  for (const i of c.inlets) patches.push(patch(`${i.id}Inlet`, `${i.id}InletFaceSet`, 'patch'))
  for (const o of c.outlets) patches.push(patch(`${o.id}Outlet`, `${o.id}OutletFaceSet`, 'patch'))
  return (
    FOAM_HEADER('dictionary', 'createPatchDict', 'system') +
    `
pointSync false;

patches
(
${patches.join('\n')}
);
`
  )
}

// Fan momentum + heat energy as fvOptions cell-zone sources.
function fvOptions(c: AirflowCase): string {
  const blocks: string[] = []
  for (const f of c.fans) {
    // Approximate jet acceleration: reach target speed over ~0.3 s of residence.
    const accel = f.speed / 0.3
    const a: [number, number, number] = [
      f.direction[0] * accel,
      f.direction[1] * accel,
      f.direction[2] * accel,
    ]
    blocks.push(`${f.id}Source
{
    type            semiImplicitSource;
    selectionMode   cellZone;
    cellZone        ${f.id}Zone;
    volumeMode      specific;
    injectionRateSuSp
    {
        U  (${vec(a)} 0);
    }
}`)
  }
  for (const h of c.heat) {
    // Heat as an enthalpy source. Map a few K of warmth to ~W/m^3 (heuristic).
    const power = Math.max(0, h.deltaT) * 120
    blocks.push(`${h.id}Source
{
    type            semiImplicitSource;
    selectionMode   cellZone;
    cellZone        ${h.id}Zone;
    volumeMode      specific;
    injectionRateSuSp
    {
        h  (${power} 0);
    }
}`)
  }
  return FOAM_HEADER('dictionary', 'fvOptions', 'system') + '\n' + blocks.join('\n\n') + '\n'
}

// Structured sample grid the backend reads back to the web viewer.
function sampleGridDict(c: AirflowCase): string {
  const { width: W, height: H, depth: D } = c.room
  const nx = 32
  const ny = 14
  const nz = 24
  return (
    FOAM_HEADER('dictionary', 'sampleGrid', 'system') +
    `
// Used via: postProcess -func sampleGrid
type            surfaces;
libs            ("libsampling.so");

// A uniform internal grid sampled into VTK; the backend converts it to the
// web viewer's velocity volume. nx=${nx} ny=${ny} nz=${nz} over the room.
interpolationScheme cellPoint;
setFormat       raw;
fields          ( U T );

sets
(
    grid
    {
        type    cloud;
        axis    xyz;
        points  GRID_POINTS_PLACEHOLDER;
    }
);

// Room extent: x[${-W / 2}, ${W / 2}] y[0, ${H}] z[${-D / 2}, ${D / 2}]
`
  )
}

