// One axis-aligned (yaw-rotated) box as an ASCII STL solid.
function boxStl(o: BoxObstacle): string {
  const hw = o.w / 2
  const hd = o.d / 2
  const cos = Math.cos(o.yaw)
  const sin = Math.sin(o.yaw)
  // 8 corners (yaw about Y), y from 0..h.
  const corner = (sx: number, sz: number, y: number): [number, number, number] => {
    const lx = sx * hw
    const lz = sz * hd
    return [o.cx + lx * cos - lz * sin, y, o.cz + lx * sin + lz * cos]
  }
  const v = [
    corner(-1, -1, 0),
    corner(1, -1, 0),
    corner(1, 1, 0),
    corner(-1, 1, 0),
    corner(-1, -1, o.h),
    corner(1, -1, o.h),
    corner(1, 1, o.h),
    corner(-1, 1, o.h),
  ]
  // 12 triangles (2 per face), outward winding.
  const faces: Array<[number, number, number]> = [
    [0, 2, 1], [0, 3, 2], // bottom
    [4, 5, 6], [4, 6, 7], // top
    [0, 1, 5], [0, 5, 4], // -z
    [2, 3, 7], [2, 7, 6], // +z
    [1, 2, 6], [1, 6, 5], // +x
    [3, 0, 4], [3, 4, 7], // -x
  ]
  const tri = (a: number, b: number, c: number) => {
    const n = normal(v[a], v[b], v[c])
    return `  facet normal ${n[0]} ${n[1]} ${n[2]}
    outer loop
      vertex ${v[a].join(' ')}
      vertex ${v[b].join(' ')}
      vertex ${v[c].join(' ')}
    endloop
  endfacet`
  }
  return `solid ${o.id}\n${faces.map((f) => tri(f[0], f[1], f[2])).join('\n')}\nendsolid ${o.id}\n`
}

function normal(
  a: [number, number, number],
  b: [number, number, number],
  c: [number, number, number],
): [number, number, number] {
  const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]]
  const w = [c[0] - a[0], c[1] - a[1], c[2] - a[2]]
  const n: [number, number, number] = [
    u[1] * w[2] - u[2] * w[1],
    u[2] * w[0] - u[0] * w[2],
    u[0] * w[1] - u[1] * w[0],
  ]
  const len = Math.hypot(n[0], n[1], n[2]) || 1
  return [n[0] / len, n[1] / len, n[2] / len]
}

