// Accurate engine: turn the engine-neutral AirflowCase into a complete
// OpenFOAM case (buoyantSimpleFoam, steady buoyant indoor air).
//
// The output is a flat map of { relativePath: fileContents }. The local
// backend writes these verbatim to a run directory and executes ./Allrun.
//
// Design choices (kept deliberately conventional so a stock OpenFOAM.com /
// ESI build runs it):
//   - Room  -> blockMesh hex box with six named wall patches.
//   - AC    -> a real velocity+temperature inlet patch carved from the rear
//              wall with topoSet + createPatch (the dominant, well-posed BC).
//   - Vent  -> a pressure outlet patch carved from the rear wall.
//   - Fan   -> an fvOptions momentum (jet) source in a sphere cellZone.
//   - Heat  -> fvOptions energy sources for warm bodies / lamp (buoyancy).
//   - Furniture -> ASCII STL boxes refined in by snappyHexMesh.
//
// This is a faithful starting case. Because it is generated without a live
// OpenFOAM to validate against, the backend reports the real solver log so
// first-run tuning (mesh counts, relaxation) is visible to the user.

import type { AirflowCase, BoxObstacle } from '../airflowCase.ts'

export interface OpenFoamCase {
  name: string
  /** relativePath -> file contents. */
  files: Record<string, string>
  /** Names of the carved inlet/outlet patches, for reference. */
  patches: { inlets: string[]; outlets: string[] }
}

const FOAM_HEADER = (cls: string, object: string, location?: string) =>
  `/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: generated by interactive_airflow      |
|  \\\\    /   O peration     |                                                 |
|   \\\\  /    A nd           | Accurate engine case export                     |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/
FoamFile
{
    version     2.0;
    format      ascii;
    class       ${cls};${location ? `\n    location    "${location}";` : ''}
    object      ${object};
}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //
`

const vec = (v: [number, number, number]) => `(${v[0]} ${v[1]} ${v[2]})`

export function exportOpenFoamCase(c: AirflowCase): OpenFoamCase {
  const files: Record<string, string> = {}
  const inletNames = c.inlets.map((i) => `${i.id}Inlet`)
  const outletNames = c.outlets.map((o) => `${o.id}Outlet`)

  files['system/controlDict'] = controlDict()
  files['system/fvSchemes'] = fvSchemes()
  files['system/fvSolution'] = fvSolution()
  files['system/blockMeshDict'] = blockMeshDict(c)
  files['system/topoSetDict'] = topoSetDict(c)
  files['system/createPatchDict'] = createPatchDict(c)
  files['system/fvOptions'] = fvOptions(c)
  files['system/sampleGrid'] = sampleGridDict(c)

  files['constant/g'] = gFile()
  files['constant/thermophysicalProperties'] = thermophysicalProperties(c)
  files['constant/turbulenceProperties'] = turbulenceProperties()

  files['0/U'] = fieldU(c, inletNames, outletNames)
  files['0/T'] = fieldT(c, inletNames, outletNames)
  files['0/p_rgh'] = fieldPrgh(inletNames, outletNames)
  files['0/p'] = fieldP(inletNames, outletNames)

  // Furniture obstacles as STL surfaces + snappyHexMesh setup.
  if (c.obstacles.length > 0) {
    files['system/snappyHexMeshDict'] = snappyHexMeshDict(c)
    files['system/meshQualityDict'] = meshQualityDict()
    for (const o of c.obstacles) {
      files[`constant/triSurface/${o.id}.stl`] = boxStl(o)
    }
  }

  files['Allrun'] = allrun(c)
  files['Allclean'] = allclean()
  files['case.json'] = JSON.stringify(c, null, 2)
  files['README.md'] = caseReadme(c, inletNames, outletNames)

  return { name: c.name, files, patches: { inlets: inletNames, outlets: outletNames } }
}

