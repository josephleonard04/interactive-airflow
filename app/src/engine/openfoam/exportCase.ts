function wallEntries(patches: string[], body: string): string {
  return patches.map((p) => `    ${p}\n    {\n${body}\n    }`).join('\n')
}

function fieldU(c: AirflowCase, inlets: string[], outlets: string[]): string {
  const inletBlocks = c.inlets
    .map((i, idx) => {
      const u: [number, number, number] = [
        i.normal[0] * i.speed,
        i.normal[1] * i.speed,
        i.normal[2] * i.speed,
      ]
      return `    ${inlets[idx]}
    {
        type            fixedValue;
        value           uniform ${vec(u)};
    }`
    })
    .join('\n')
  const outletBlocks = wallEntries(
    outlets,
    `        type            pressureInletOutletVelocity;\n        value           uniform (0 0 0);`,
  )
  return (
    FOAM_HEADER('volVectorField', 'U', '0') +
    `
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (0 0 0);

boundaryField
{
    "(floor|ceiling|backWall|frontWall|leftWall|rightWall)"
    {
        type            noSlip;
    }
${inletBlocks}
${outletBlocks}
}
`
  )
}

function fieldT(c: AirflowCase, inlets: string[], outlets: string[]): string {
  const inletBlocks = c.inlets
    .map(
      (i, idx) => `    ${inlets[idx]}
    {
        type            fixedValue;
        value           uniform ${i.temperature};
    }`,
    )
    .join('\n')
  const outletBlocks = wallEntries(outlets, `        type            inletOutlet;\n        inletValue      uniform ${c.ambientTemperature};\n        value           uniform ${c.ambientTemperature};`)
  return (
    FOAM_HEADER('volScalarField', 'T', '0') +
    `
dimensions      [0 0 0 1 0 0 0];
internalField   uniform ${c.ambientTemperature};

boundaryField
{
    "(floor|ceiling|backWall|frontWall|leftWall|rightWall)"
    {
        type            zeroGradient;
    }
${inletBlocks}
${outletBlocks}
}
`
  )
}

function fieldPrgh(inlets: string[], outlets: string[]): string {
  const inletBlocks = wallEntries(inlets, `        type            fixedFluxPressure;\n        value           uniform 0;`)
  const outletBlocks = wallEntries(outlets, `        type            prghPressure;\n        p               uniform 0;\n        value           uniform 0;`)
  return (
    FOAM_HEADER('volScalarField', 'p_rgh', '0') +
    `
dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform 0;

boundaryField
{
    "(floor|ceiling|backWall|frontWall|leftWall|rightWall)"
    {
        type            fixedFluxPressure;
        value           uniform 0;
    }
${inletBlocks}
${outletBlocks}
}
`
  )
}

function fieldP(inlets: string[], outlets: string[]): string {
  const all = [...inlets, ...outlets]
  const extra = all.length
    ? '\n' + wallEntries(all, `        type            calculated;\n        value           uniform 1e5;`)
    : ''
  return (
    FOAM_HEADER('volScalarField', 'p', '0') +
    `
dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform 1e5;

boundaryField
{
    "(floor|ceiling|backWall|frontWall|leftWall|rightWall)"
    {
        type            calculated;
        value           uniform 1e5;
    }${extra}
}
`
  )
}

